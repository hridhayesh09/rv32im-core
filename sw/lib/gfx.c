void gfx_rect(int x, int y, int w, int h, int colour)
{
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > GFX_WIDTH)  w = GFX_WIDTH - x;
    if (y + h > GFX_HEIGHT) h = GFX_HEIGHT - y;
    for (int row = 0; row < h; row++) {
        volatile uint8_t *p = VGA_FB + (y + row) * GFX_WIDTH + x;
        for (int col = 0; col < w; col++)
            p[col] = (uint8_t)colour;
    }
}

void gfx_clear(int colour)
{
    gfx_rect(0, 0, GFX_WIDTH, GFX_HEIGHT, colour);
}

static const uint8_t *glyph(char c)
{
    if (c >= 'a' && c <= 'z')
        c -= 'a' - 'A';
    for (int i = 0; FONT_CHARS[i]; i++)
        if (FONT_CHARS[i] == c)
            return FONT[i];
    return FONT[0];
}

void gfx_text(int x, int y, const char *s, int colour, int scale)
{
    for (; *s; s++, x += 6 * scale) {
        const uint8_t *g = glyph(*s);
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++)
                if (g[row] & (0x10 >> col))
                    gfx_rect(x + col * scale, y + row * scale, scale, scale, colour);
    }
}

int gfx_text_width(const char *s, int scale)
{
    int n = 0;
    while (s[n])
        n++;
    return n ? (6 * n - 1) * scale : 0;
}

void gfx_wait_vblank(void)
{
    uint32_t frame = VGA_FRAME;
    while (VGA_FRAME == frame)
        ;
}

void gfx_set_palette(int index, uint32_t rgb12)
{
    VGA_PALETTE(index) = rgb12 & 0xFFF;
}
